"""Reproducible run reports (Markdown for people, JSON for tools).

A report ties a result to everything needed to reproduce it: module/analysis, the exact
input reference (dataset id + content hash, channel, Kepler TCE or sample), every setting,
the model version and its held-out metrics, timings, the result headline, per-item metrics
where ground truth exists, and the human review verdicts.
"""
from __future__ import annotations

import json

from spaceml.common.utils import now_iso, read_json
from spaceml.config import RUNS_DIR

from . import registry
from .db import tx


def _fmt(v) -> str:
    if isinstance(v, float):
        return f"{v:.4g}"
    if isinstance(v, (list, dict)):
        return json.dumps(v)[:200]
    return str(v)


def _pct(v) -> str:
    return "n/a" if v is None else f"{v:.1%}"


def build(run: dict) -> tuple[dict, str]:
    result = read_json(RUNS_DIR / run["id"] / "result.json") if run.get("result_path") else None
    with tx() as c:
        reviews = [dict(r) for r in c.execute("SELECT item, verdict, note, updated_at FROM reviews WHERE run_id=?",
                                              (run["id"],))]
    model_eval = None
    if run.get("model_version") and run["module"] in registry.MODULES:
        ev = next((e for e in registry.evaluations(run["module"]) if e["version"] == run["model_version"]), None)
        model_eval = ev["metrics"].get("headline") if ev else None
    dataset = None
    inp = run.get("input_ref") or {}
    if run["module"] == "workbench":
        try:
            from spaceml.workbench.store import get
            m = get(inp["dataset_id"])
            dataset = {"id": m["id"], "name": m["name"], "kind": m["kind"], "sha256": m.get("sha256"),
                       "created_at": m.get("created_at"), "summary": m.get("summary")}
        except Exception:  # noqa: BLE001
            dataset = {"id": inp.get("dataset_id"), "note": "dataset deleted since the run"}

    data = {
        "report_generated_at": now_iso(),
        "run": {k: run.get(k) for k in ("id", "module", "status", "error", "input_label", "model_version",
                                        "created_at", "started_at", "finished_at", "duration_ms", "summary")},
        "input": inp, "dataset": dataset, "model_heldout_headline": model_eval,
        "reviews": reviews, "result": result,
    }

    L = [f"# Run report · {run['input_label']}", "",
         f"- **Run id:** `{run['id']}`  ",
         f"- **Module:** {run['module']}" + (f" · analysis `{inp.get('analysis')}`" if inp.get("analysis") else ""),
         f"- **Status:** {run['status']}" + (f" - {run['error']}" if run.get("error") else ""),
         f"- **Origin:** {'bundled reference run (starter pack)' if run.get('origin') == 'bundled' else 'computed on this machine'}"
         + (f" · repeat of `{run['repeat_of']}`" if run.get("repeat_of") else ""),
         f"- **Created:** {run['created_at']} · duration {run.get('duration_ms') or 0} ms",
         f"- **Model version:** {run.get('model_version') or 'none (no trained model needed)'}"]
    if model_eval:
        L.append(f"- **Model held-out {model_eval['metric']}:** {model_eval['model']:.4g} "
                 f"(baseline {model_eval['baseline']:.4g})")
    if dataset:
        L += ["", "## Dataset", f"- **Name:** {dataset.get('name')}  ", f"- **Id:** `{dataset.get('id')}`",
              f"- **Content hash (sha256/16):** `{dataset.get('sha256')}`", f"- **Contents:** {dataset.get('summary')}"]
    L += ["", "## Input and settings", "", "| Setting | Value |", "|---|---|"]
    params = inp.get("params", inp)
    for k, v in params.items():
        L.append(f"| {k} | {_fmt(v)} |")
    if run.get("summary"):
        L += ["", "## Result", "", f"**{run['summary'].get('headline', '')}**"]
    if result:
        L += _result_section(run["module"], inp.get("analysis"), result)
    if reviews:
        L += ["", "## Human review", "", "| Item | Verdict | Note | Updated |", "|---|---|---|---|"]
        L += [f"| {r['item']} | {r['verdict']} | {r['note'] or ''} | {r['updated_at']} |" for r in reviews]
    L += ["", "---", "Generated by Space ML Mission Control. Re-run with the same dataset hash, settings and "
          "model version to reproduce this result."]
    return data, "\n".join(L) + "\n"


def _result_section(module: str, analysis: str | None, r: dict) -> list[str]:
    L: list[str] = []
    if module == "telemetry":
        s, b = r["score"], r["baseline_score"]
        L += ["", "| | LSTM + dynamic threshold | z-score baseline |", "|---|---|---|",
              f"| Labeled anomalies found | {s['tp']}/{len(r['labeled'])} | {b['tp']}/{len(r['labeled'])} |",
              f"| False alarms | {s['fp']} | {b['fp']} |", "", "### Flagged intervals"]
        L += [f"- steps {f['start']}-{f['end']} (peak error {f['peak_error']:.4g})" for f in r["flagged"]] or ["- none"]
    elif module == "exoplanet":
        L += ["", f"- Candidate score: {r.get('candidate_score')}", f"- Baseline score: {r.get('baseline_score')}",
              f"- Period {r['tce']['period_days']:.5f} d · duration {r['tce']['duration_hours']:.2f} h · depth "
              f"{r['tce']['depth_ppm']:.0f} ppm", f"- Catalog label: {r.get('catalog_label')} · split: {r.get('split')}"]
    elif module == "mars" or analysis == "image.terrain":
        L += [""] + [f"- {c}: {_pct(v)}" for c, v in r["class_shares"].items()]
        loc = r.get("location")
        if loc:
            L.append(f"- Location: sol {loc.get('sol')} · site {loc.get('site')} / drive {loc.get('drive')} · "
                     f"precision {loc.get('precision')}" + (f" · {loc['lat']:.5f}°N {loc['lon']:.5f}°E"
                                                            if loc.get("lat") is not None else ""))
        if r.get("evaluation"):
            e = r["evaluation"]
            L.append(f"- Mean IoU vs expert label: {_pct(e['model']['miou'])} (all-soil {_pct(e['baseline']['miou'])})")
    elif analysis == "timeseries.anomaly":
        m = r.get("metrics")
        if m:
            L += ["", "| | Rolling robust | z-score baseline |", "|---|---|---|"]
            for k in ("precision", "recall", "f1"):
                L.append(f"| {k} | {_pct(m['robust'][k])} | {_pct(m['zscore'][k])} |")
            L.append(f"| false alarms | {m['robust']['fp']} | {m['zscore']['fp']} |")
        units = {c["name"]: c.get("unit") for c in r.get("channels", []) if c.get("unit")}
        if units:
            L += ["", "Units: " + ", ".join(f"{k} [{v}]" for k, v in units.items())]
        for key in ("robust", "zscore"):
            L += ["", f"### {r[key]['name']}"]
            L += [f"- {i['x0']} → {i['x1']} ({i['length']} steps)" for i in r[key]["intervals"][:100]] or ["- none"]
    elif module == "spaceweather":
        w = r["window"]
        L += ["", f"Window {w['start']} → {w['end']} · issued hourly · inputs up to the issuance hour only "
                  f"(causality check: {'passed' if r['causality_check']['passed'] else 'FAILED'})",
              f"Model {r['model']['version']} trained on {r['model']['train_years'][0]}-{r['model']['train_years'][-1]}"
              + (f" - **in-sample for {r['in_sample_years']}**" if r.get("in_sample_years") else " - out-of-sample for this window"),
              "", "| Horizon | RMSE model | RMSE persistence | Skill | Model better (h) | Persistence better (h) | "
                  "First storm warning (lead h) |", "|---|---|---|---|---|---|---|"]
        for h in r["horizons"]:
            v = r["per_horizon"][str(h)]
            fw = (v.get("first_warning") or {}).get("lead_hours")
            L.append(f"| +{h} h | {_fmt(v['rmse'])} | {_fmt(v['rmse_persistence'])} | {_fmt(v['skill'])} | "
                     f"{v['better_hours']} | {v['worse_hours']} | {'n/a' if fw is None else fw} |")
        L += ["", "### Timeline (detected from the data)"]
        L += [f"- {e['time'][:16]}Z - {e['label']}: {e['detail']}" for e in r["timeline"]] or ["- none"]
        L += ["", "### Data"] + [f"- OMNI2 {p['year']}: Dst {p['dst_status']}, sha256 {str(p.get('cache_sha256'))[:16]}…"
                                 for p in r.get("data_provenance", [])]
    elif analysis == "image.change":
        L += ["", f"- Method: {r['method']} · threshold {r['threshold']:.4g}",
              f"- Changed: {_pct(r['changed_fraction'])} of valid pixels"
              + (f" · {r['changed_area_km2']:.4g} km²" if r.get("changed_area_km2") is not None else ""),
              f"- Area basis: {r['area_basis']}", f"- Valid overlap: {_pct(r['valid_fraction'])}"]
        L += [f"- Note: {n}" for n in r.get("notes", [])]
        L += ["", "### Largest regions"] + [
            f"- #{i + 1}: {g['pixels']} px" + (f" ({g['area_km2']:.4g} km²)" if g.get("area_km2") else "")
            + f", bbox {g['bbox']}" for i, g in enumerate(r["regions"])]
    return L
